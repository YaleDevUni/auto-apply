"""회사명·제목 정규화와 canonical_key 생성.

canonical_key는 중복지원 방어선이다(`apply_ledger`의 UNIQUE 컬럼). 같은 자리가
자소설·사람인·원티드에 각각 올라와도 키가 같아야 두 번 지원하지 않는다.

정규화 강도의 트레이드오프가 여기서 결정된다.

  너무 약하면 — '(주)토스'와 '토스'가 다른 키가 되어 **같은 자리에 두 번 지원한다**.
  너무 세면  — '웹 서비스 기획'과 '앱 서비스 기획'이 같은 키가 되어 **한 자리를 통째로 놓친다**.

완전 자동화에서는 두 실패의 무게가 다르다. 중복지원은 사람이 수습해야 하는 사고고,
누락은 다음 수집 때 또 볼 기회가 있다. 그래서 **애매하면 합치는 쪽**으로 기울인다.
단, 직무를 가르는 단어(웹/앱/프론트/백엔드 등)는 상투어 제거 대상에서 뺀다 — 그건
합치면 안 되는 진짜 구분이다.
"""

from __future__ import annotations

import hashlib
import re

# 회사명에서 걷어낼 법인격 표기
_LEGAL = re.compile(
    r"\(주\)|\(유\)|\(재\)|\(사\)|주식회사|유한회사|재단법인|사단법인|"
    r"\bco\.?,?\s*ltd\.?|\binc\.?|\bcorp\.?|\bllc\b",
    re.IGNORECASE,
)

# 제목에서 걷어낼 상투어. 직무를 가르지 못하는 단어만 넣는다.
#
# '웹', '앱', '프론트', '백엔드' 같은 것은 절대 넣지 않는다. 이노션의
# '웹 서비스 기획'과 '앱 서비스 기획'은 다른 자리인데, 이걸 지우면 하나로 뭉쳐
# 한 자리를 통째로 놓친다.
_BOILERPLATE = re.compile(
    # 연도는 '2026년'만이 아니라 맨 '2026'으로도 온다 ('[2026 상반기] …'가 제일 흔하다).
    # 20xx로 한정해 제목 속 일반 숫자(예: '3D', '100')를 건드리지 않는다.
    r"20\d{2}\s*년?도?|\d+분기|상·?하반기|상반기|하반기|수시|공개|공채|채용|모집|"
    r"신입\s*및\s*경력|신입/경력|경력직|신입직?|인턴십?|정규직|계약직|"
    r"[○◯●◆■▶★☆]|\bnew\b|\bhot\b|\d+차",
    re.IGNORECASE,
)

_BRACKET = re.compile(r"[\[\](){}<>【】〔〕«»]")
_PUNCT = re.compile(r"[·・,./\\|~\-–—_:;!?\"'`]+")
_SPACE = re.compile(r"\s+")

# 괄호로 감싼 덩어리 전체 (내용 포함)
_PAREN_GROUP = re.compile(r"[(（\[［][^)）\]］]*[)）\]］]")
# 그중 내용이 라틴문자·숫자·공백뿐인 것 = 영문 병기
_PAREN_LATIN = re.compile(r"[(（\[［][\sA-Za-z0-9&.,'’\-]*[)）\]］]")


def company(name: str) -> str:
    """'(주) 라스트스프링(LASTSPRING)' → '라스트스프링'

    회사명 괄호는 법인격 아니면 영문/한글 병기다. 어느 쪽도 회사를 가르지 않으므로
    통째로 지운다. 원티드는 '라스트스프링(LASTSPRING)', 사람인은 '라스트스프링'으로
    같은 회사를 다르게 적는다 — 안 지우면 같은 자리에 두 번 지원한다.
    """
    s = _LEGAL.sub(" ", name or "")
    s = _PAREN_GROUP.sub(" ", s)
    s = _BRACKET.sub(" ", s)
    s = _PUNCT.sub(" ", s)
    return _SPACE.sub("", s).strip().lower()


def title(raw: str) -> str:
    """'[2026 상반기] 백엔드 개발자 신입 채용' → '백엔드개발자'

    제목 괄호는 회사명과 달리 **의미를 담을 수 있다**. '개발자(백엔드)'와
    '개발자(프론트엔드)'는 다른 자리다. 그래서 통째로 지우지 않고 갈라서 쓴다.

        괄호 안이 라틴문자뿐  → 영문 병기다. 지운다.
                                 '영업지원 (Sales support)' ≡ '영업지원'
        괄호 안에 한글이 있음 → 직무 구분일 수 있다. 괄호만 벗기고 내용은 남긴다.
                                 '개발자(백엔드)' ≢ '개발자(프론트엔드)'
    """
    s = _PAREN_LATIN.sub(" ", raw or "")
    s = _BRACKET.sub(" ", s)
    s = _BOILERPLATE.sub(" ", s)
    s = _PUNCT.sub(" ", s)
    return _SPACE.sub("", s).strip().lower()


def canonical_key(company_name: str, job_title: str) -> str:
    """지원 원장의 유일키. 회사+직무가 같으면 플랫폼이 달라도 같은 키가 나온다.

    해시로 줄이는 이유는 길이가 아니라 안정성이다. 원문을 그대로 키로 쓰면
    보이지 않는 공백·유니코드 변형이 키를 갈라놓는다.
    """
    c, t = company(company_name), title(job_title)
    if not c and not t:
        # 둘 다 비면 키를 만들 수 없다. 호출부가 이걸 원장에 넣으면 안 된다.
        return ""
    return hashlib.sha256(f"{c}|{t}".encode("utf-8")).hexdigest()[:20]
